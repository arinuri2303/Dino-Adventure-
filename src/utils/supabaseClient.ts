export interface SupabaseLeaderboardRow {
  id?: number;
  created_at?: string;
  timestamp?: string;
  nama: string;
  kelas: string;
  skor_kuis_subbab?: number;
  skor_palu_gunung?: number;
  skor_asesmen_c1c3?: number;
  skor_asesmen_c4c6?: number;
  total_skor?: number;
  // Support camelCase columns as fallback if table was created with camelCase
  skorKuisSubBab?: number;
  skorPaluGunung?: number;
  skorAsesmenC1C3?: number;
  skorAsesmenC4C6?: number;
  totalSkor?: number;
}

export async function fetchScoresFromSupabase(
  tableName: string = DEFAULT_SUPABASE_TABLE
): Promise<{ data: LeaderboardEntry[] | null; error: string | null }> {
  try {
    const { data, error } = await supabase
      .from(tableName)
      .select('*')
      .order('total_skor', { ascending: false })
      .limit(100);

    if (error) {
      return { data: null, error: error.message };
    }

    const mapped: LeaderboardEntry[] = (data || []).map((row: SupabaseLeaderboardRow) => ({
      timestamp:
        row.timestamp ||
        (row.created_at ? new Date(row.created_at).toLocaleString('id-ID') : new Date().toLocaleString('id-ID')),
      nama: row.nama || 'Siswa SD',
      kelas: row.kelas || 'Kelas 4',
      skorKuisSubBab: Number(row.skor_kuis_subbab ?? row.skorKuisSubBab ?? 0),
      skorPaluGunung: Number(row.skor_palu_gunung ?? row.skorPaluGunung ?? 0),
      skorAsesmenC1C3: Number(row.skor_asesmen_c1c3 ?? row.skorAsesmenC1C3 ?? 0),
      skorAsesmenC4C6: Number(row.skor_asesmen_c4c6 ?? row.skorAsesmenC4C6 ?? 0),
      totalSkor: Number(row.total_skor ?? row.totalSkor ?? 0)
    }));

    return { data: mapped, error: null };
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : 'Gagal terhubung ke Supabase';
    return { data: null, error: msg };
  }
}

export async function insertScoreToSupabase(
  entry: LeaderboardEntry,
  tableName: string = DEFAULT_SUPABASE_TABLE
): Promise<{ ok: boolean; error: string | null }> {
  try {
    const payload = {
      timestamp: entry.timestamp,
      nama: entry.nama,
      kelas: entry.kelas,
      skor_kuis_subbab: entry.skorKuisSubBab,
      skor_palu_gunung: entry.skorPaluGunung,
      skor_asesmen_c1c3: entry.skorAsesmenC1C3,
      skor_asesmen_c4c6: entry.skorAsesmenC4C6,
      total_skor: entry.totalSkor
    };

    const { error } = await supabase.from(tableName).insert([payload]);

    if (error) {
      return { ok: false, error: error.message };
    }
    return { ok: true, error: null };
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : 'Gagal menyimpan ke Supabase';
    return { ok: false, error: msg };
  }
}
